def check_git_preconditions(skip_check: bool = False) -> str:
    """Verify that working tree is clean and local HEAD matches origin/main.

    Returns the short commit hash of HEAD.
    """
    repo_root = BACKEND_DIR.parent
    if skip_check:
        try:
            return subprocess.check_output(
                ["git", "rev-parse", "--short", "HEAD"],
                cwd=str(repo_root),
                text=True,
            ).strip()
        except Exception:
            return "latest"

    # 1. Check working directory status
    status_proc = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=str(repo_root),
        capture_output=True,
        text=True,
        check=True,
    )
    dirty = status_proc.stdout.strip()
    if dirty:
        raise RuntimeError(
            f"Precondition failed: git working tree is dirty. Stash or commit all changes first:\n{dirty}"
        )

    # 2. Check local HEAD equals origin/main
    head_rev = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=str(repo_root),
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()

    origin_rev = subprocess.run(
        ["git", "rev-parse", "origin/main"],
        cwd=str(repo_root),
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()

    if head_rev != origin_rev:
        raise RuntimeError(
            f"Precondition failed: local HEAD ({head_rev[:7]}) does not match origin/main ({origin_rev[:7]}). "
            f"Push or pull changes so local HEAD matches origin/main before refreshing demo snapshot."
        )

    short_sha = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        cwd=str(repo_root),
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    return short_sha


def collect_code_chunks() -> list[tuple[str, int, str]]:
    """Parse real code files from bounded scope (app/ai, app/services, app/models)
    and chunk them using the real smart_chunk_code pipeline.
    """
    targets = [
        BACKEND_DIR / "app" / "ai",
        BACKEND_DIR / "app" / "services",
        BACKEND_DIR / "app" / "models",
    ]

    all_chunks: list[tuple[str, int, str]] = []
    scanned_files = 0

    for target_dir in targets:
        if not target_dir.exists():
            continue
        for root, _dirs, files in os.walk(target_dir):
            if "__pycache__" in root:
                continue
            for file_name in sorted(files):
                if not file_name.endswith(".py") or file_name.startswith("__"):
                    continue
                file_path = Path(root) / file_name
                rel_path = str(file_path.relative_to(BACKEND_DIR)).replace("\\", "/")

                try:
                    with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                        code = f.read()
                    if not code.strip():
                        continue

                    file_chunks = smart_chunk_code(code, rel_path)
                    for chunk_idx, chunk_text in enumerate(file_chunks):
                        all_chunks.append((rel_path, chunk_idx, chunk_text))
                    scanned_files += 1
                except Exception as e:
                    print(f"Warning: Failed to chunk {rel_path}: {e}")

    print(f"  [Parser] Scanned {scanned_files} Python source files across app/ai, app/services, app/models")
    return all_chunks


async def cleanup_staging_repo(
    session,
    staging_repo_id: UUID | None = None,
    user_id: UUID | None = None,
) -> None:
    """Clean up temporary staging repository and all its child records."""
    target_ids: list[UUID] = []
    if staging_repo_id:
        target_ids.append(staging_repo_id)
    elif user_id:
        res = await session.execute(
            select(Repository.id).where(
                Repository.user_id == user_id,
                Repository.full_name == DEMO_STAGING_REPO_FULL_NAME,
            )
        )
        target_ids = list(res.scalars().all())

    for rid in target_ids:
        await session.execute(delete(Embedding).where(Embedding.repo_id == rid))
        await session.execute(delete(CodeHealth).where(CodeHealth.repo_id == rid))
        await session.execute(delete(ArchitectureDiagram).where(ArchitectureDiagram.repo_id == rid))
        await session.execute(delete(Repository).where(Repository.id == rid))
    await session.commit()


async def atomic_swap_staging_to_live(
    session,
    live_repo_id: UUID,
    staging_repo_id: UUID,
    demo_repo_desc: str,
) -> None:
    """Atomically swap staging repository data to live repository in ONE transaction."""
    session.expire_all()

    # 1. Delete live repository's existing child records
    await session.execute(delete(Embedding).where(Embedding.repo_id == live_repo_id))
    await session.execute(delete(CodeHealth).where(CodeHealth.repo_id == live_repo_id))
    await session.execute(delete(ArchitectureDiagram).where(ArchitectureDiagram.repo_id == live_repo_id))

    # 2. Re-point staging child records to live repository ID
    await session.execute(
        update(Embedding)
        .where(Embedding.repo_id == staging_repo_id)
        .values(repo_id=live_repo_id)
    )
    await session.execute(
        update(CodeHealth)
        .where(CodeHealth.repo_id == staging_repo_id)
        .values(repo_id=live_repo_id)
    )
    await session.execute(
        update(ArchitectureDiagram)
        .where(ArchitectureDiagram.repo_id == staging_repo_id)
        .values(repo_id=live_repo_id)
    )

    # 3. Update live repository row with latest status and description
    await session.execute(
        update(Repository)
        .where(Repository.id == live_repo_id)
        .values(
            description=demo_repo_desc,
            indexing_status=IndexingStatus.COMPLETE,
            indexing_progress=100,
            indexing_error=None,
            last_indexed_at=datetime.now(UTC),
        )
    )

    # 4. Delete the staging repository row
    await session.execute(delete(Repository).where(Repository.id == staging_repo_id))
    await session.commit()


async def populate_repo_pipeline(
    session,
    target_repo: Repository,
    chunks: list[tuple[str, int, str]],
    simulate_failure_step: str | None = None,
    rate_limit_delay: int = 10,
) -> tuple[int, dict, str]:
    """Execute chunk embedding, code health analysis, and architecture diagram generation."""
    embedding_repo = EmbeddingRepository(session)
    health_repo = CodeHealthRepository(session)
    arch_repo = ArchitectureDiagramRepository(session)

    # A. Embeddings
    print(f"\n[Pipeline] Embedding {len(chunks)} chunks for repo '{target_repo.full_name}'...")
    existing_paths_res = await session.execute(
        select(Embedding.file_path, Embedding.chunk_index).where(
            Embedding.repo_id == target_repo.id
        )
    )
    already_done = {(r[0], r[1]) for r in existing_paths_res.fetchall()}
    remaining = [(fp, ci, ct) for fp, ci, ct in chunks if (fp, ci) not in already_done]

    if remaining:
        embedding_service = EmbeddingService()
        batch_size = 5
        total_inserted = len(already_done)

        for batch_start in range(0, len(remaining), batch_size):
            if simulate_failure_step == "embedding" and total_inserted > 0:
                raise RuntimeError("Simulated failure during embedding step")

            batch = remaining[batch_start:batch_start + batch_size]
            batch_texts = [ct for _, _, ct in batch]

            response = await embedding_service.orchestrator.embed_batch(
                batch_texts, agent="embedding"
            )
            batch_embeddings = response.embeddings

            batch_data = []
            for (fp, ci, ct), emb in zip(batch, batch_embeddings, strict=False):
                batch_data.append({
                    "repo_id": target_repo.id,
                    "file_path": fp,
                    "chunk_index": ci,
                    "chunk_text": ct,
                    "embedding": emb,
                })
            await embedding_repo.create_bulk(batch_data)
            await session.commit()
            total_inserted += len(batch_data)
            print(f"    Batch {batch_start // batch_size + 1}: {total_inserted}/{len(chunks)} embeddings")

            if batch_start + batch_size < len(remaining) and rate_limit_delay > 0:
                await asyncio.sleep(rate_limit_delay)

    final_emb_res = await session.execute(
        select(func.count()).select_from(Embedding).where(Embedding.repo_id == target_repo.id)
    )
    emb_count = final_emb_res.scalar_one()

    if simulate_failure_step == "health":
        raise RuntimeError("Simulated failure before health analysis step")

    # B. Real Code Health Analysis
    print("\n[Pipeline] Running CodeHealthService.analyze()...")
    health_service = CodeHealthService()
    try:
        health_result = await health_service.analyze(
            repository=target_repo,
            embedding_repo=embedding_repo,
            health_repo=health_repo,
        )
    except AnalysisUnavailableError as e:
        raise RuntimeError(f"Code health analysis failed: {e}") from e

    print(f"  Overall Score: {health_result.get('overall_score', 'N/A')}/100")

    if simulate_failure_step == "architecture":
        raise RuntimeError("Simulated failure before architecture diagram step")

    # C. Real Architecture Diagram
    print("\n[Pipeline] Generating Architecture Diagram from embeddings...")
    arch_analyzer = CodeStructureAnalyzer()
    arch_structure = await arch_analyzer.from_embeddings(
        repo_id=target_repo.id,
        session=session,
    )
    arch_service = ArchitectureVisualizationService(session)
    mermaid_code = arch_service._generate_mermaid_from_structure(arch_structure, "mermaid")

    existing_diagrams = await arch_repo.get_by_repo(target_repo.id)
    if existing_diagrams:
        await arch_repo.delete_by_repo(target_repo.id)
    await arch_repo.create(
        repo_id=target_repo.id,
        name="DevIntel Core Architecture",
        diagram_type="mermaid",
        mermaid_code=mermaid_code,
    )
    print("  Architecture diagram created successfully.")

    return emb_count, health_result, mermaid_code


async def seed_demo(
    refresh: bool = False,
    skip_git_check: bool = False,
    simulate_failure_step: str | None = None,
    rate_limit_delay: int = 10,
) -> None:
    """Main seed function."""
    start_time = time.time()
    commit_sha = check_git_preconditions(skip_check=skip_git_check)
    demo_repo_desc = (
        f"Snapshot of backend modules app/ai, app/services and app/models at commit {commit_sha}"
    )

    print("=" * 70)
    print("DevIntel AI — Demo Repository Seeder")
    print(f"Mode: {'ATOMIC REFRESH' if refresh else 'IDEMPOTENT SEED'}")
    print(f"Target Commit: {commit_sha}")
    print(f"Description:   {demo_repo_desc}")
    if simulate_failure_step:
        print(f"SIMULATE FAILURE AT: {simulate_failure_step.upper()}")
    print("=" * 70)

    async with AsyncSessionLocal() as session:
        user_repo = UserRepository(session)
        repo_repo = RepositoryRepository(session)

        # 1. Ensure demo user exists
        print("\n1. Ensuring Demo User...")
        user = await user_repo.get_by_email(DEMO_EMAIL)
        if not user:
            print(f"  Creating demo user: {DEMO_EMAIL}")
            user = await user_repo.get_or_create_demo_user(
                email=DEMO_EMAIL,
                hashed_password=hash_password(DEMO_PASSWORD),
                full_name=DEMO_FULL_NAME,
            )
            await session.commit()
        print(f"  Demo user ready: ID={user.id} ({user.email})")

        # 2. Check Live Repository
        print("\n2. Checking Live Demo Repository...")
        live_repo = await repo_repo.get_by_full_name(DEMO_REPO_FULL_NAME, user_id=user.id)
        if not live_repo:
            legacy_repo = await repo_repo.get_by_full_name("devintel/devintel-core", user_id=user.id)
            if legacy_repo:
                print(f"  Renaming legacy demo repo '{legacy_repo.full_name}' to '{DEMO_REPO_FULL_NAME}'...")
                await repo_repo.update(
                    legacy_repo.id,
                    full_name=DEMO_REPO_FULL_NAME,
                    repo_name=DEMO_REPO_NAME,
                    description=demo_repo_desc,
                    url=f"https://github.com/{DEMO_REPO_FULL_NAME}",
                )
                await session.commit()
                live_repo = await repo_repo.get_by_id(legacy_repo.id)

        if not live_repo:
            print(f"  Creating live repository record: {DEMO_REPO_FULL_NAME}")
            live_repo = await repo_repo.create(
                user_id=user.id,
                full_name=DEMO_REPO_FULL_NAME,
                repo_name=DEMO_REPO_NAME,
                description=demo_repo_desc,
                url=f"https://github.com/{DEMO_REPO_FULL_NAME}",
                stars=142,
                language="Python",
                default_branch="main",
                indexing_status=IndexingStatus.PENDING,
                indexing_progress=0,
                indexing_mode="standard",
            )
            await session.commit()

        # Print current baseline stats for live repo
        live_emb_res = await session.execute(
            select(func.count()).select_from(Embedding).where(Embedding.repo_id == live_repo.id)
        )
        live_emb_count = live_emb_res.scalar_one()
        live_health_res = await session.execute(
            select(CodeHealth.overall_score).where(CodeHealth.repo_id == live_repo.id)
        )
        live_health_score = live_health_res.scalar_one_or_none()

        live_repo_id = live_repo.id
        live_repo_desc = live_repo.description
        print(f"  Live Repo ID:          {live_repo_id}")
        print(f"  Live Status:           {live_repo.indexing_status}")
        print(f"  Live Embeddings Count: {live_emb_count}")
        print(f"  Live Health Score:     {live_health_score}")
        print(f"  Live Description:      {live_repo_desc}")

        chunks = collect_code_chunks()
        if not chunks:
            raise RuntimeError("No code chunks generated! Check search paths.")

        # Non-refresh mode: check idempotency
        if not refresh:
            if live_repo.indexing_status == IndexingStatus.COMPLETE and live_emb_count >= len(chunks):
                print(
                    f"\n[IDEMPOTENT] Live repo '{DEMO_REPO_FULL_NAME}' is already complete "
                    f"with {live_emb_count}/{len(chunks)} embeddings. Skipping."
                )
                return
            # Otherwise seed live repo directly
            print("\nSeeding live repository directly...")
            await populate_repo_pipeline(
                session, live_repo, chunks, rate_limit_delay=rate_limit_delay
            )
            await repo_repo.update(
                live_repo_id,
                description=demo_repo_desc,
                indexing_status=IndexingStatus.COMPLETE,
                indexing_progress=100,
                indexing_error=None,
                last_indexed_at=datetime.now(UTC),
            )
            await session.commit()
            print(f"\nSUCCESS: Live repo {live_repo_id} seeded successfully.")
            return

        # ----------------------------------------------------------------------
        # ATOMIC REFRESH FLOW:
        # 1. Clean up any previous staging repo
        # 2. Build into staging repo
        # 3. Swap staging rows into live repo in ONE transaction
        # 4. On any failure, destroy staging repo and leave live repo untouched
        # ----------------------------------------------------------------------
        print("\n3. Starting Atomic Refresh via Staging Repository...")
        await cleanup_staging_repo(session, user_id=user.id)

        print(f"  Creating temporary staging repository '{DEMO_STAGING_REPO_FULL_NAME}'...")
        staging_repo = await repo_repo.create(
            user_id=user.id,
            full_name=DEMO_STAGING_REPO_FULL_NAME,
            repo_name=f"{DEMO_REPO_NAME}-staging",
            description=f"Temporary staging repo for refresh at commit {commit_sha}",
            url=f"https://github.com/{DEMO_REPO_FULL_NAME}",
            stars=142,
            language="Python",
            default_branch="main",
            indexing_status=IndexingStatus.INDEXING,
            indexing_progress=10,
            indexing_mode="standard",
        )
        await session.commit()
        staging_repo_id = staging_repo.id
        print(f"  Staging Repository created: ID={staging_repo_id}")

        try:
            emb_count, health_result, mermaid_code = await populate_repo_pipeline(
                session=session,
                target_repo=staging_repo,
                chunks=chunks,
                simulate_failure_step=simulate_failure_step,
                rate_limit_delay=rate_limit_delay,
            )
        except Exception as exc:
            print(f"\n[STAGING FAILED] Error during staging build: {exc}")
            print(f"  Cleaning up staging repository {staging_repo_id}...")
            await cleanup_staging_repo(session, staging_repo_id=staging_repo_id)
            print("  [ROLLBACK COMPLETE] Staging repository deleted.")

            # Verify live repository remains untouched
            live_emb_verify = await session.execute(
                select(func.count()).select_from(Embedding).where(Embedding.repo_id == live_repo_id)
            )
            live_health_verify = await session.execute(
                select(CodeHealth.overall_score).where(CodeHealth.repo_id == live_repo_id)
            )
            print(f"  [UNTOUCHED] Live Repo ID:          {live_repo_id}")
            print(f"  [UNTOUCHED] Live Embeddings Count: {live_emb_verify.scalar_one()} (was {live_emb_count})")
            print(f"  [UNTOUCHED] Live Health Score:     {live_health_verify.scalar_one_or_none()} (was {live_health_score})")
            print(f"  [UNTOUCHED] Live Description:      {live_repo_desc}")
            raise

        # Staging succeeded: Atomic swap to live repo
        print("\n4. Atomic Swap: Moving staging data to live repository in ONE transaction...")
        await atomic_swap_staging_to_live(
            session=session,
            live_repo_id=live_repo_id,
            staging_repo_id=staging_repo_id,
            demo_repo_desc=demo_repo_desc,
        )

        total_time = time.time() - start_time
        print("\n" + "=" * 70)
        print(f"SUCCESS: Atomic refresh completed in {total_time:.2f}s!")
        print(f"  Live Repository ID: {live_repo_id} (unchanged)")
        print(f"  Full Name:          {DEMO_REPO_FULL_NAME}")
        print(f"  Description:        {demo_repo_desc}")
        print(f"  Chunks/Vectors:     {emb_count}")
        print(f"  Health Score:       {health_result.get('overall_score', 'N/A')}/100")
        print(f"  User:               {DEMO_EMAIL}")
        print("=" * 70 + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Seed or refresh demo repository data.")
