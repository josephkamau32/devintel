"""Offline seed script for DevIntel AI demo repository.

Creates or ensures the demo user (demo@devintel.dev) exists and indexes a real,
bounded scope of backend code (app/ai, app/services, app/models) through the real
smart_chunk_code pipeline and real Gemini embedding provider call.

Health scores are generated by calling CodeHealthService.analyze() — the same
pipeline used during real indexing — NOT hardcoded values.

Idempotent: check-then-insert/skip. Re-running is a clean no-op.
"""

